// One-off helper: copies the colour ramps of Homepage's own theme.css into a
// JavaScript table, so the editor can show the official colour of a palette and
// put a palette back to it.
import https from 'node:https';
import { writeFileSync } from 'node:fs';

const REV = '51cc1684f9f34a7877ed462b8f94c9cc687b4dde';
const url = 'https://raw.githubusercontent.com/gethomepage/homepage/' + REV + '/src/styles/theme.css';

const body = await new Promise((resolve, reject) => {
  https.get(url, (res) => {
    let text = '';
    res.on('data', (chunk) => { text += chunk; });
    res.on('end', () => resolve(text));
  }).on('error', reject);
});

const SHADE_NAMES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900'];
const out = [];
const re = /\.theme-([a-z]+)\s*\{([\s\S]*?)\}/g;
let match;
while ((match = re.exec(body))) {
  const id = match[1];
  const block = match[2];
  const shades = SHADE_NAMES.map((name) => {
    const found = block.match(new RegExp('--color-' + name + ':\\s*([\\d\\s/]+);'));
    return found ? found[1].replace(/\/\s*\d+%$/, '').trim() : '';
  });
  const logoStart = (block.match(/--color-logo-start:\s*([^;]+);/) || [, '0 0 0'])[1].trim();
  const logoStop = (block.match(/--color-logo-stop:\s*([^;]+);/) || [, '0 0 0'])[1].trim();
  const shadeList = shades.map((s) => "'" + s + "'").join(', ');
  out.push('  ' + id + ": { shades: [" + shadeList + "], logoStart: '" + logoStart + "', logoStop: '" + logoStop + "' },");
}

const header = [
  "// The colour ramps of Homepage's built-in palettes, copied from the theme.css",
  '// of Homepage v2.6.0. They are the official colours, used to show what a',
  '// palette looks like untouched and to put a palette back to it.',
  '//',
  '// Generated by tools/gen-official-shades.mjs. Do not edit by hand.',
  'const OFFICIAL_SHADES = {'
].join('\n');

writeFileSync('lib/official-shades.js',
  header + '\n' + out.join('\n') + '\n};\nmodule.exports = { OFFICIAL_SHADES };\n');

console.log('themes written:', out.length);
